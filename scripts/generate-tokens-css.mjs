import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { tokens } from '../src/tokens/tokens.ts';

const dirname = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(dirname, '../src/tokens/tokens.generated.css');

function kebabCase(key) {
  return key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

const lines = ['/* AUTO-GENERATED by scripts/generate-tokens-css.mjs from src/tokens/tokens.ts. Do not edit by hand. */', '@theme {'];

for (const [key, value] of Object.entries(tokens.color)) {
  lines.push(`  --color-${kebabCase(key)}: ${value};`);
}

lines.push(`  --font-display: var(--font-display-loaded), ${tokens.font.display};`);
lines.push(`  --font-body: var(--font-body-loaded), ${tokens.font.body};`);
lines.push(`  --font-mono: ${tokens.font.mono};`);

for (const [key, value] of Object.entries(tokens.size)) {
  lines.push(`  --text-${key}: ${value};`);
}

for (const [key, value] of Object.entries(tokens.tracking)) {
  lines.push(`  --tracking-${key}: ${value};`);
}

tokens.space.forEach((value, index) => {
  lines.push(`  --spacing-${index}: ${value}px;`);
});

for (const [key, value] of Object.entries(tokens.radius)) {
  lines.push(`  --radius-${key}: ${value};`);
}

for (const [key, value] of Object.entries(tokens.shadow)) {
  lines.push(`  --shadow-${key}: ${value};`);
}

for (const [key, value] of Object.entries(tokens.z)) {
  lines.push(`  --z-index-${key}: ${value};`);
}

for (const [key, value] of Object.entries(tokens.bp)) {
  lines.push(`  --breakpoint-${key}: ${value};`);
}

lines.push('}', '');
lines.push(':root {');
for (const [key, value] of Object.entries(tokens.motion)) {
  lines.push(`  --motion-${key}: ${value};`);
}
lines.push('}', '');

writeFileSync(outFile, lines.join('\n'));
console.log(`Wrote ${path.relative(process.cwd(), outFile)}`);
